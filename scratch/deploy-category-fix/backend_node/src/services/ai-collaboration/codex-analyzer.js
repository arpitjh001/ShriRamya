/**
 * Codex Analyzer Service
 *
 * Senior reviewer and debugging system that analyzes Qwen output
 * and provides structured correction prompts.
 */

const axios = require('axios');
const config = require('../../config/ai-collaboration.config');
const logger = require('../../utils/logger');
const QualityScorer = require('./quality-scorer');
const CollaborationLogger = require('./collaboration-logger');

class CodexAnalyzer {
  constructor() {
    this.endpoint = config.models.codex.endpoint;
    this.model = config.models.codex.model;
    this.timeout = config.models.codex.timeout;
    this.temperature = config.models.codex.temperature;
    this.maxTokens = config.models.codex.maxTokens;
    this.qualityScorer = new QualityScorer();
  }

  /**
   * Analyze code generated by Qwen
   * @param {Object} params - Analysis parameters
   * @param {string} params.code - Code to analyze
   * @param {string} params.userRequest - Original user request
   * @param {Object} params.context - Additional context
   * @param {CollaborationLogger} params.collabLogger - Logger instance
   * @param {number} params.iteration - Current iteration number
   * @returns {Promise<Object>} Codex review results
   */
  async analyze({ code, userRequest, context = {}, collabLogger = null, iteration = 1 }) {
    const prompt = this._buildAnalysisPrompt(code, userRequest, context);

    try {
      const response = await axios.post(
        this.endpoint,
        {
          model: this.model,
          prompt: prompt,
          temperature: this.temperature,
          max_tokens: this.maxTokens,
          stream: false
        },
        {
          timeout: this.timeout,
          headers: {
            'Content-Type': 'application/json'
          }
        }
      );

      const generatedText = this._extractGeneratedCode(response.data);
      const reviewResult = this._parseReviewResult(generatedText, code);

      // Calculate quality scores
      const qualityResult = this.qualityScorer.calculate(reviewResult);
      
      reviewResult.quality_score = qualityResult.totalScore;
      reviewResult.detailed_scores = qualityResult.detailedScores;
      reviewResult.passed_threshold = qualityResult.passedThreshold;

      // Generate correction prompt
      reviewResult.correction_prompt = this._generateCorrectionPrompt(reviewResult);

      if (collabLogger) {
        collabLogger.logCodexReview(iteration, reviewResult);
      }

      logger.info(`[Codex] Analysis completed - Iteration ${iteration}`, {
        qualityScore: reviewResult.quality_score,
        passedThreshold: reviewResult.passed_threshold,
        errorsCount: reviewResult.errors?.length || 0,
        architectureIssuesCount: reviewResult.architecture_issues?.length || 0,
        securityIssuesCount: reviewResult.security_issues?.length || 0
      });

      return reviewResult;
    } catch (error) {
      logger.error('[Codex] Analysis failed', {
        iteration,
        error: error.message,
        endpoint: this.endpoint
      });

      if (collabLogger) {
        collabLogger.logError(error, { iteration, stage: 'codex_analysis' });
      }

      // Return a conservative review on error
      return this._generateFallbackReview(error);
    }
  }

  /**
   * Validate code against specific criteria
   * @param {Object} params - Validation parameters
   * @param {string} params.code - Code to validate
   * @param {Array<string>} params.criteria - Validation criteria
   * @returns {Promise<Object>} Validation results
   */
  async validate({ code, criteria = [] }) {
    const prompt = this._buildValidationPrompt(code, criteria);

    try {
      const response = await axios.post(
        this.endpoint,
        {
          model: this.model,
          prompt: prompt,
          temperature: this.temperature,
          max_tokens: this.maxTokens,
          stream: false
        },
        {
          timeout: this.timeout,
          headers: {
            'Content-Type': 'application/json'
          }
        }
      );

      const generatedText = this._extractGeneratedCode(response.data);
      return this._parseValidationResult(generatedText);
    } catch (error) {
      logger.error('[Codex] Validation failed', {
        error: error.message
      });

      return {
        valid: false,
        errors: [`Validation failed: ${error.message}`],
        warnings: []
      };
    }
  }

  /**
   * Build the code analysis prompt
   * @private
   */
  _buildAnalysisPrompt(code, userRequest, context) {
    const contextInfo = this._formatContext(context);

    return `You are Codex, a senior software architect and code reviewer. Your task is to thoroughly analyze code for errors, security vulnerabilities, architecture issues, and performance problems.

## Original Request
${userRequest}

## Context
${contextInfo}

## Code to Analyze
\`\`\`
${code}
\`\`\`

## Analysis Checklist

### 1. Syntax Errors
- Check for syntax errors, parsing errors, type errors
- Check for missing imports or dependencies
- Check for undefined variables or functions

### 2. Runtime Errors
- Check for potential null/undefined access
- Check for unhandled exceptions
- Check for race conditions or async issues

### 3. API Contract Mismatch
- Check if API endpoints match expected patterns
- Check request/response format consistency
- Check error handling consistency

### 4. Architecture Issues
- Check for proper separation of concerns
- Check for tight coupling
- Check for missing abstraction layers
- Check for proper layer organization (controller-service-repository)

### 5. Security Vulnerabilities
- Check for SQL injection risks
- Check for XSS vulnerabilities
- Check for hardcoded secrets or credentials
- Check for missing authentication/authorization
- Check for input validation
- Check for proper error handling (no sensitive data leaks)

### 6. Performance Issues
- Check for N+1 query problems
- Check for missing caching opportunities
- Check for inefficient loops or algorithms
- Check for memory leak risks
- Check for unoptimized database queries

### 7. Code Style Problems
- Check for consistent naming conventions
- Check for proper code formatting
- Check for adequate documentation/comments

## Output Format
You MUST respond with a JSON object in this exact format:

{
  "syntax_errors": ["<error1>", "<error2>"],
  "parsing_errors": ["<error1>"],
  "type_errors": ["<error1>"],
  "missing_imports": ["<import1>"],
  "runtime_errors": ["<error1>"],
  "api_contract_issues": ["<issue1>"],
  "architecture_issues": ["<issue1>", "<issue2>"],
  "soc_violations": ["<violation1>"],
  "tight_coupling": ["<coupling1>"],
  "missing_abstractions": ["<abstraction1>"],
  "security_issues": [
    {"severity": "critical|high|medium|low", "description": "<issue>"}
  ],
  "has_unvalidated_input": false,
  "has_sql_injection_risk": false,
  "has_xss_risk": false,
  "has_hardcoded_secrets": false,
  "missing_auth_check": false,
  "performance_issues": ["<issue1>"],
  "n_plus_one_queries": ["<issue1>"],
  "missing_caching_opportunities": false,
  "inefficient_loops": ["<loop1>"],
  "memory_leak_risks": ["<risk1>"],
  "unoptimized_queries": ["<query1>"],
  "style_issues": ["<issue1>"],
  "good_patterns": ["<pattern1>"],
  "errors": ["<summary error1>", "<summary error2>"],
  "architecture_improvements": ["<improvement1>"],
  "security_recommendations": ["<recommendation1>"],
  "performance_recommendations": ["<recommendation1>"]
}

## Important
- Be thorough but fair in your analysis
- Prioritize critical issues (security, syntax errors)
- Provide actionable feedback
- Acknowledge good patterns when present

Respond ONLY with the JSON object, no additional text.`;
  }

  /**
   * Build validation prompt for specific criteria
   * @private
   */
  _buildValidationPrompt(code, criteria) {
    return `You are Codex, a code validation expert. Validate the following code against these criteria:

## Criteria
${criteria.map((c, i) => `${i + 1}. ${c}`).join('\n')}

## Code to Validate
\`\`\`
${code}
\`\`\`

## Output Format
Respond with JSON:
{
  "valid": true/false,
  "errors": ["<error1>"],
  "warnings": ["<warning1>"],
  "passed_criteria": [1, 2],
  "failed_criteria": [3]
}

Respond ONLY with the JSON object.`;
  }

  /**
   * Extract generated code from API response
   * @private
   */
  _extractGeneratedCode(responseData) {
    if (responseData.text) {
      return responseData.text;
    }
    if (responseData.choices?.[0]?.text) {
      return responseData.choices[0].text;
    }
    if (responseData.choices?.[0]?.message?.content) {
      return responseData.choices[0].message.content;
    }
    if (responseData.response) {
      return responseData.response;
    }
    if (responseData.output) {
      return responseData.output;
    }
    if (responseData.generated) {
      return responseData.generated;
    }
    if (typeof responseData === 'string') {
      return responseData;
    }

    return JSON.stringify(responseData);
  }

  /**
   * Parse review result from generated text
   * @private
   */
  _parseReviewResult(generatedText, code) {
    try {
      const jsonMatch = generatedText.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        const parsed = JSON.parse(jsonMatch[0]);
        
        // Ensure all expected fields exist
        return {
          syntax_errors: parsed.syntax_errors || [],
          parsing_errors: parsed.parsing_errors || [],
          type_errors: parsed.type_errors || [],
          missing_imports: parsed.missing_imports || [],
          runtime_errors: parsed.runtime_errors || [],
          api_contract_issues: parsed.api_contract_issues || [],
          architecture_issues: parsed.architecture_issues || [],
          soc_violations: parsed.soc_violations || [],
          tight_coupling: parsed.tight_coupling || [],
          missing_abstractions: parsed.missing_abstractions || [],
          security_issues: parsed.security_issues || [],
          has_unvalidated_input: parsed.has_unvalidated_input || false,
          has_sql_injection_risk: parsed.has_sql_injection_risk || false,
          has_xss_risk: parsed.has_xss_risk || false,
          has_hardcoded_secrets: parsed.has_hardcoded_secrets || false,
          missing_auth_check: parsed.missing_auth_check || false,
          performance_issues: parsed.performance_issues || [],
          n_plus_one_queries: parsed.n_plus_one_queries || [],
          missing_caching_opportunities: parsed.missing_caching_opportunities || false,
          inefficient_loops: parsed.inefficient_loops || [],
          memory_leak_risks: parsed.memory_leak_risks || [],
          unoptimized_queries: parsed.unoptimized_queries || [],
          style_issues: parsed.style_issues || [],
          good_patterns: parsed.good_patterns || [],
          errors: parsed.errors || this._summarizeErrors(parsed),
          architecture_improvements: parsed.architecture_improvements || [],
          security_recommendations: parsed.security_recommendations || [],
          performance_recommendations: parsed.performance_recommendations || []
        };
      }

      // Fallback: generate a basic review
      return this._generateBasicReview(code);
    } catch (error) {
      logger.warn('[Codex] Failed to parse JSON review', {
        error: error.message,
        generatedText: generatedText.substring(0, 200)
      });

      return this._generateBasicReview(code);
    }
  }

  /**
   * Parse validation result
   * @private
   */
  _parseValidationResult(generatedText) {
    try {
      const jsonMatch = generatedText.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        return JSON.parse(jsonMatch[0]);
      }
      return { valid: false, errors: ['Failed to parse validation result'], warnings: [] };
    } catch (error) {
      return { valid: false, errors: [error.message], warnings: [] };
    }
  }

  /**
   * Generate correction prompt from review results
   * @private
   */
  _generateCorrectionPrompt(review) {
    const instructions = [];

    // Critical errors first
    if (review.syntax_errors?.length > 0) {
      instructions.push(`Fix ${review.syntax_errors.length} syntax error(s): ${review.syntax_errors.slice(0, 3).join(', ')}`);
    }

    if (review.security_issues?.filter(i => i.severity === 'critical')?.length > 0) {
      instructions.push('Address critical security vulnerabilities immediately');
    }

    if (review.has_sql_injection_risk) {
      instructions.push('Use parameterized queries to prevent SQL injection');
    }

    if (review.has_unvalidated_input) {
      instructions.push('Add input validation for all user inputs');
    }

    // Architecture issues
    if (review.architecture_issues?.length > 0) {
      instructions.push(`Refactor to address: ${review.architecture_issues.slice(0, 3).join(', ')}`);
    }

    if (review.soc_violations?.length > 0) {
      instructions.push('Improve separation of concerns - move logic to appropriate layers');
    }

    // Performance issues
    if (review.n_plus_one_queries?.length > 0) {
      instructions.push('Optimize database queries to eliminate N+1 problems');
    }

    // General improvements
    if (review.performance_issues?.length > 0) {
      instructions.push(`Optimize: ${review.performance_issues.slice(0, 2).join(', ')}`);
    }

    if (instructions.length === 0) {
      return 'Code looks good. Minor improvements optional.';
    }

    return instructions.join('. ');
  }

  /**
   * Summarize errors from detailed analysis
   * @private
   */
  _summarizeErrors(parsed) {
    const errors = [];

    if (parsed.syntax_errors?.length > 0) {
      errors.push(`Syntax errors: ${parsed.syntax_errors.length} issue(s) found`);
    }
    if (parsed.security_issues?.length > 0) {
      errors.push(`Security issues: ${parsed.security_issues.length} vulnerability(ies) found`);
    }
    if (parsed.architecture_issues?.length > 0) {
      errors.push(`Architecture issues: ${parsed.architecture_issues.length} issue(s) found`);
    }
    if (parsed.runtime_errors?.length > 0) {
      errors.push(`Runtime errors: ${parsed.runtime_errors.length} potential issue(s) found`);
    }

    return errors;
  }

  /**
   * Generate a basic review when parsing fails
   * @private
   */
  _generateBasicReview(code) {
    return {
      syntax_errors: [],
      parsing_errors: [],
      type_errors: [],
      missing_imports: [],
      runtime_errors: [],
      api_contract_issues: [],
      architecture_issues: [],
      soc_violations: [],
      tight_coupling: [],
      missing_abstractions: [],
      security_issues: [],
      has_unvalidated_input: false,
      has_sql_injection_risk: false,
      has_xss_risk: false,
      has_hardcoded_secrets: false,
      missing_auth_check: false,
      performance_issues: [],
      n_plus_one_queries: [],
      missing_caching_opportunities: false,
      inefficient_loops: [],
      memory_leak_risks: [],
      unoptimized_queries: [],
      style_issues: [],
      good_patterns: ['Code structure appears organized'],
      errors: [],
      architecture_improvements: [],
      security_recommendations: [],
      performance_recommendations: []
    };
  }

  /**
   * Generate fallback review on error
   * @private
   */
  _generateFallbackReview(error) {
    return {
      errors: [`Analysis incomplete: ${error.message}`],
      architecture_issues: ['Review could not be completed'],
      security_issues: [{ severity: 'medium', description: 'Manual review recommended due to analysis error' }],
      performance_issues: [],
      correction_prompt: 'Please review code manually as automated analysis encountered an error.',
      quality_score: 50,
      detailed_scores: {
        syntax: 50,
        architecture: 50,
        security: 50,
        performance: 50
      },
      passed_threshold: false
    };
  }

  /**
   * Format context for prompts
   * @private
   */
  _formatContext(context) {
    if (!context || Object.keys(context).length === 0) {
      return 'No additional context provided.';
    }

    let formatted = '';

    if (context.existingFiles) {
      formatted += `Existing Files: ${context.existingFiles.join(', ')}\n`;
    }

    if (context.requirements) {
      formatted += `Requirements: ${context.requirements.join(', ')}\n`;
    }

    if (context.framework) {
      formatted += `Framework: ${context.framework}\n`;
    }

    if (context.database) {
      formatted += `Database: ${context.database}\n`;
    }

    if (context.techStack) {
      formatted += `Tech Stack: ${context.techStack.join(', ')}\n`;
    }

    return formatted || 'No additional context provided.';
  }
}

module.exports = {
  CodexAnalyzer
};
